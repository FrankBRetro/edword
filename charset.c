/* a Windows code page byte (1252, or 1250 for central Europe) in Unicode */
long win_to_uni(unsigned char c, int cp)
{
    if (c < 0x80) return c;
    if (cp == 1250) return w1250[c - 0x80] ? (long)w1250[c - 0x80] : '?';
    if (c < 0xA0) return w1252[c - 0x80] ? (long)w1252[c - 0x80] : '?';
    return c;
}

/* the Windows code page documents are written in */
int st_codepage(void) { return st_cset == ST_CS_CZECH ? 1250 : 1252; }

unsigned char st_to_win(unsigned char c)
{
    unsigned char r;
    if (c < 128) return c;
    if (st_cset == ST_CS_CZECH) {
        long u = st_to_uni(c);
        int i;
        if (u < 0x100 && u >= 0xA0 && w1250[u - 0x80] == u) return (unsigned char)u;
        for (i = 0; i < 128; i++) if (w1250[i] == u) return (unsigned char)(0x80 + i);
        return '?';
    }
    r = st2win[c - 128];
    return r ? r : '?';
}

unsigned char win_to_st(unsigned char c)
{
    int i;
    if (c < 128) return c;
    if (st_cset == ST_CS_CZECH) return uni_to_st(win_to_uni(c, 1250));
    switch (c) {
    case 0x91: case 0x92: return '\'';
    case 0x93: case 0x94: return '"';
    case 0x96: case 0x97: return '-';
    case 0x85: return '.';
    case 0x95: return 0xF9;          /* bullet */
    case 0xA0: return ' ';
    }
    for (i = 0; i < 128; i++)
        if (st2win[i] == c) return (unsigned char)(i + 128);
    return '?';
}

