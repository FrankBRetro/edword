unsigned char st_lower(unsigned char c)
{
    int i;
    const unsigned char *up = st_cset == ST_CS_CZECH ? cz_up : st_up, *lo = st_cset == ST_CS_CZECH ? cz_lo : st_lo;
    if (c >= 'A' && c <= 'Z') return (unsigned char)(c + 32);
    for (i = 0; up[i]; i++) if (up[i] == c) return lo[i];
    return c;
}

unsigned char st_upper(unsigned char c)
{
    int i;
    const unsigned char *up = st_cset == ST_CS_CZECH ? cz_up : st_up, *lo = st_cset == ST_CS_CZECH ? cz_lo : st_lo;
    if (c >= 'a' && c <= 'z') return (unsigned char)(c - 32);
    for (i = 0; lo[i]; i++) if (lo[i] == c) return up[i];
    return c;
}

int st_isalpha(unsigned char c)
{
    if (st_cset == ST_CS_CZECH)
        return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= 0x80 && c <= 0xAB) ||
               (c >= 0xB0 && c <= 0xB8) || c == 0xC0 || c == 0xC1;
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
           (c >= 0x80 && c <= 0x9A) || c == 0x9E ||
           (c >= 0xA0 && c <= 0xA5) || (c >= 0xB0 && c <= 0xB8) ||
           c == 0xC0 || c == 0xC1;
}
