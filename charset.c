long st_to_uni(unsigned char c)
{
    if (st_cset == ST_CS_CZECH && c >= 0x80 && c < 0x80 + 44) return kam_uni[c - 0x80];
    return c < 0x80 ? c : st_uni[c - 0x80];
}

/* letters with accents the ST lacks, as the plain letter: U+00C0..U+017F */
static const char base_lat[] =
    "AAAAAAACEEEEIIIIDNOOOOOxOUUUUYTsaaaaaaaceeeeiiiidnooooo/ouuuuyty"
    "AaAaAaCcCcCcCcDdDdEeEeEeEeEeGgGgGgGgHhHhIiIiIiIiIiJjJjKkkLlLlLlL"
    "lLlNnNnNnnNnOoOoOoOoRrRrRrSsSsSsSsTtTtTtUuUuUuUuUuUuWwYyYZzZzZzs";

/* Unicode code point (from RTF \uN, UTF-8 or UTF-16) -> ST: the same
 * character if the ST has it, else something close, else '?' */
unsigned char uni_to_st(long u)
{
    int i;
    if (u < 0) u += 65536L;
    if (u < 0x80) return (unsigned char)u;
    if (st_cset == ST_CS_CZECH) {
        for (i = 0; i < 44; i++) if (kam_uni[i] == u) return (unsigned char)(0x80 + i);
        for (i = 44; i < 128; i++) if (st_uni[i] == u) return (unsigned char)(0x80 + i);
    } else
        for (i = 0; i < 128; i++) if (st_uni[i] == u) return (unsigned char)(0x80 + i);
    switch (u) {
    case 0x2018: case 0x2019: case 0x201A: case 0x201B: case 0x2032: case 0x2039: case 0x203A: return '\'';
    case 0x201C: case 0x201D: case 0x201E: case 0x201F: case 0x2033: return '"';
    case 0x2010: case 0x2011: case 0x2012: case 0x2013: case 0x2014: case 0x2015: case 0x2212: case 0x00AD: return '-';
    case 0x2219: case 0x25CF: case 0x25E6: case 0x2043: return 0xF9;
    case 0x2026: return '.';
    case 0x00A0: case 0x2002: case 0x2003: case 0x2004: case 0x2005: case 0x2006: case 0x2007:
    case 0x2008: case 0x2009: case 0x200A: case 0x202F: case 0x3000: return ' ';
    case 0x00D7: return 'x';
    case 0x00B9: return '1';
    case 0x20AC: return 'E';
    case 0x00A4: return '$';
    case 0x00A6: return '|';
    case 0x2021: return 0xBB;
    case 0x2030: return '%';
    case 0x2044: case 0x2215: return '/';
    case 0x03BC: return 0xE6;
    case 0x02C6: return '^';
    case 0x02DC: return '~';
    case 0xFEFF: case 0x200B: case 0x200C: case 0x200D: return ' ';
    }
    if (u >= 0xC0 && u < 0x180) return (unsigned char)base_lat[u - 0xC0];
    if (st_cset == ST_CS_CZECH) return '?';
    if (u >= 0x80 && u < 0x100) {                 /* the rest of Latin-1, through Windows */
        unsigned char c = win_to_st((unsigned char)u);
        if (c != '?') return c;
    }
    for (i = 0; i < 32; i++)
        if (w1252[i] == u) return win_to_st((unsigned char)(0x80 + i));
    return '?';
}

/* upper/lower case pairs among the ST accented letters */
